// JSON bridge (conformance tests only)

fn to_json_expr(schema: &Schema, ty: &Type, x: &str) -> String {
    match ty {
        Type::U8 | Type::U16 | Type::U32 | Type::Millis | Type::Bool | Type::F64 | Type::Str(_) => {
            x.to_string()
        }
        Type::U64 | Type::I64 => format!("{x}.toString()"),
        Type::Bytes(_) => format!("toHex({x})"),
        Type::List(_, inner) => format!("{x}.map((x) => {})", to_json_expr(schema, inner, "x")),
        Type::Opt(inner) => format!(
            "({x} === undefined ? null : {})",
            to_json_expr(schema, inner, x)
        ),
        Type::Record => format!("recordToJson({x})"),
        Type::Records => format!("{x}.map(recordToJson)"),
        Type::Named(name) => match schema.enum_named(name) {
            Some(_) => format!("({name}Names[{x}] ?? {x})"),
            None => format!("{name}ToJson({x})"),
        },
    }
}

fn from_json_expr(schema: &Schema, ty: &Type, x: &str) -> String {
    match ty {
        Type::U8 | Type::U16 | Type::U32 | Type::Millis => format!("Number({x})"),
        Type::U64 | Type::I64 => format!("BigInt({x})"),
        Type::Bool => format!("Boolean({x})"),
        Type::F64 => format!("Number({x})"),
        Type::Str(_) => format!("String({x})"),
        Type::Bytes(_) => format!("fromHex({x})"),
        Type::List(_, inner) => format!(
            "({x} as unknown[]).map((x) => {})",
            from_json_expr(schema, inner, "x")
        ),
        Type::Opt(inner) => format!(
            "({x} === null || {x} === undefined ? undefined : {})",
            from_json_expr(schema, inner, x)
        ),
        Type::Record => format!("recordFromJson({x})"),
        Type::Records => format!("({x} as unknown[]).map(recordFromJson)"),
        Type::Named(name) => match schema.enum_named(name) {
            Some(_) => format!("enumFromJson(P.{name}, {x})"),
            None => format!("{name}FromJson({x})"),
        },
    }
}

pub fn emit_json(schema: &Schema) -> String {
    let mut o = String::new();
    header(&mut o);
    writeln!(o, "//").unwrap();
    writeln!(
        o,
        "// JSON bridge for the conformance suite: the same JSON mapping as"
    )
    .unwrap();
    writeln!(
        o,
        "// protocol/fixtures (u64 as decimal strings, bytes as hex, absent as null)."
    )
    .unwrap();
    writeln!(o).unwrap();
    writeln!(o, "import * as P from \"./kronosdb-protocol.ts\";").unwrap();
    writeln!(
        o,
        "import type {{ Frame, StoredRecord }} from \"./kronosdb-protocol.ts\";"
    )
    .unwrap();
    for e in &schema.enums {
        writeln!(
            o,
            "import {{ {}Names }} from \"./kronosdb-protocol.ts\";",
            e.name
        )
        .unwrap();
    }
    writeln!(o).unwrap();
    writeln!(
        o,
        "// eslint-disable-next-line @typescript-eslint/no-explicit-any"
    )
    .unwrap();
    writeln!(o, "type J = any;").unwrap();
    o.push_str(
        r#"
const toHex = (b: Uint8Array): string => Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
function fromHex(j: J): Uint8Array {
  if (j !== null && typeof j === "object" && typeof j.utf8 === "string") return new TextEncoder().encode(j.utf8);
  const s = String(j);
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(s.slice(2 * i, 2 * i + 2), 16);
  return out;
}
function enumFromJson(values: Readonly<Record<string, number>>, j: J): number {
  return typeof j === "string" ? values[j] : Number(j);
}
"#,
    );
    for u in &schema.unions {
        emit_union_json(&mut o, schema, u);
    }
    for s in &schema.structs {
        writeln!(o).unwrap();
        writeln!(o, "export function {0}ToJson(v: P.{0}): J {{", s.name).unwrap();
        if s.fields.is_empty() {
            writeln!(o, "  void v;").unwrap();
        }
        writeln!(o, "  return {{").unwrap();
        for f in &s.fields {
            writeln!(
                o,
                "    {}: {},",
                f.name,
                to_json_expr(schema, &f.ty, &format!("v.{}", camel(&f.name)))
            )
            .unwrap();
        }
        writeln!(o, "  }};").unwrap();
        writeln!(o, "}}").unwrap();
        writeln!(o).unwrap();
        writeln!(o, "export function {0}FromJson(j: J): P.{0} {{", s.name).unwrap();
        if s.fields.is_empty() {
            writeln!(o, "  void j;").unwrap();
        }
        writeln!(o, "  return {{").unwrap();
        for f in &s.fields {
            writeln!(
                o,
                "    {}: {},",
                camel(&f.name),
                from_json_expr(schema, &f.ty, &format!("j.{}", f.name))
            )
            .unwrap();
        }
        writeln!(o, "  }};").unwrap();
        writeln!(o, "}}").unwrap();
    }
    write!(
        o,
        r#"
export function recordToJson(r: StoredRecord): J {{
  return {{ flags: r.flags, event: {e}ToJson(r.event) }};
}}

export function recordFromJson(j: J): StoredRecord {{
  return {{ flags: Number(j.flags), event: {e}FromJson(j.event) }};
}}
"#,
        e = EVENT_RECORD
    )
    .unwrap();
    writeln!(o).unwrap();
    writeln!(o, "export function frameBodyToJson(frame: Frame): J {{").unwrap();
    writeln!(o, "  switch (frame.name) {{").unwrap();
    for f in schema.frames() {
        writeln!(o, "    case \"{0}\": return {0}ToJson(frame.body);", f.name).unwrap();
    }
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
    writeln!(o).unwrap();
    writeln!(
        o,
        "export function frameFromJson(name: string, body: J): Frame {{"
    )
    .unwrap();
    writeln!(o, "  switch (name) {{").unwrap();
    for f in schema.frames() {
        writeln!(
            o,
            "    case \"{0}\": return {{ name: \"{0}\", body: {0}FromJson(body) }};",
            f.name
        )
        .unwrap();
    }
    writeln!(
        o,
        "    default: throw new Error(`unknown frame ${{name}}`);"
    )
    .unwrap();
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
    o
}

fn emit_union(o: &mut String, schema: &Schema, u: &Union) {
    writeln!(o).unwrap();
    jsdoc(o, "", &u.doc);
    writeln!(o, "export type {} =", u.name).unwrap();
    for v in &u.variants {
        writeln!(
            o,
            "  | {{ kind: \"{}\"; value: {} }}",
            camel(&v.name),
            ts_type(schema, &v.ty)
        )
        .unwrap();
    }
    writeln!(o, "  ;").unwrap();
    writeln!(o).unwrap();
    writeln!(o, "export function decode{0}(r: Reader): {0} {{", u.name).unwrap();
    writeln!(o, "  const tag = readU8(r);").unwrap();
    writeln!(o, "  switch (tag) {{").unwrap();
    for v in &u.variants {
        writeln!(
            o,
            "    case {}: return {{ kind: \"{}\", value: {} }};",
            v.tag,
            camel(&v.name),
            decode_expr(schema, &v.ty)
        )
        .unwrap();
    }
    writeln!(
        o,
        "    default: throw new ProtocolError(`{} has no variant with tag ${{tag}}`);",
        u.name
    )
    .unwrap();
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
    writeln!(o).unwrap();
    writeln!(
        o,
        "export function encode{0}(w: Writer, v: {0}): void {{",
        u.name
    )
    .unwrap();
    writeln!(o, "  switch (v.kind) {{").unwrap();
    for v in &u.variants {
        let ctx = format!("{}.{}", u.name, v.name);
        writeln!(o, "    case \"{}\":", camel(&v.name)).unwrap();
        writeln!(o, "      writeU8(w, {});", v.tag).unwrap();
        writeln!(
            o,
            "      {}",
            encode_stmt(schema, &v.ty, "v.value", &ctx, 0)
        )
        .unwrap();
        writeln!(o, "      break;").unwrap();
    }
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
}

fn emit_union_json(o: &mut String, schema: &Schema, u: &Union) {
    writeln!(o).unwrap();
    writeln!(o, "export function {0}ToJson(v: P.{0}): J {{", u.name).unwrap();
    writeln!(o, "  switch (v.kind) {{").unwrap();
    for v in &u.variants {
        writeln!(
            o,
            "    case \"{}\": return {{ {}: {} }};",
            camel(&v.name),
            v.name,
            to_json_expr(schema, &v.ty, "v.value")
        )
        .unwrap();
    }
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
    writeln!(o).unwrap();
    writeln!(o, "export function {0}FromJson(j: J): P.{0} {{", u.name).unwrap();
    writeln!(
        o,
        "  const [key, value] = Object.entries(j)[0] as [string, J];"
    )
    .unwrap();
    writeln!(o, "  switch (key) {{").unwrap();
    for v in &u.variants {
        writeln!(
            o,
            "    case \"{}\": return {{ kind: \"{}\", value: {} }};",
            v.name,
            camel(&v.name),
            from_json_expr(schema, &v.ty, "value")
        )
        .unwrap();
    }
    writeln!(
        o,
        "    default: throw new Error(`{} has no variant ${{key}}`);",
        u.name
    )
    .unwrap();
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
}
