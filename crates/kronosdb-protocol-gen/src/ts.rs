//! Emits the TypeScript codec (`protocol/ts/kronosdb-protocol.ts`) and its
//! JSON bridge for the conformance suite (`protocol/ts/kronosdb-protocol-json.ts`).
//!
//! Only erasable syntax is generated — no `enum`, no `namespace`, no
//! parameter properties — so the files run under Node's type stripping,
//! Bun, Deno and browsers as they are, with no dependencies.

use std::fmt::Write;

use crate::schema::{EVENT_RECORD, Enum, Schema, Struct, Type, Union, Width};

const RUNTIME: &str = include_str!("ts_runtime.ts");

/// Schema names are snake_case; TypeScript properties are camelCase.
fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper = false;
    for c in name.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.push(c.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn header(o: &mut String) {
    writeln!(
        o,
        "// @generated by protocol-gen from protocol/kronosdb.schema. Do not edit;"
    )
    .unwrap();
    writeln!(o, "// change the schema and run `just protocol`.").unwrap();
}

fn jsdoc(o: &mut String, indent: &str, lines: &[String]) {
    if lines.is_empty() {
        return;
    }
    writeln!(o, "{indent}/**").unwrap();
    for line in lines {
        if line.is_empty() {
            writeln!(o, "{indent} *").unwrap();
        } else {
            writeln!(o, "{indent} * {}", line.replace("*/", "* /")).unwrap();
        }
    }
    writeln!(o, "{indent} */").unwrap();
}

fn ts_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::U8 | Type::U16 | Type::U32 | Type::Millis => "number".into(),
        Type::U64 | Type::I64 => "bigint".into(),
        Type::Bool => "boolean".into(),
        Type::F64 => "number".into(),
        Type::Str(_) => "string".into(),
        Type::Bytes(_) => "Uint8Array".into(),
        Type::List(_, inner) => format!("{}[]", ts_type(schema, inner)),
        Type::Opt(inner) => ts_type(schema, inner),
        Type::Record => "StoredRecord".into(),
        Type::Records => "StoredRecord[]".into(),
        Type::Named(name) => match schema.enum_named(name) {
            Some(_) => "number".into(),
            None => name.clone(),
        },
    }
}

fn w(w: Width) -> &'static str {
    match w {
        Width::W16 => "16",
        Width::W32 => "32",
    }
}

fn decode_expr(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::U8 => "readU8(r)".into(),
        Type::U16 => "readU16(r)".into(),
        Type::U32 => "readU32(r)".into(),
        Type::U64 => "readU64(r)".into(),
        Type::I64 => "readI64(r)".into(),
        Type::Millis => "readMillis(r)".into(),
        Type::Bool => "readBool(r)".into(),
        Type::F64 => "readF64(r)".into(),
        Type::Str(wd) => format!("readStr{}(r)", w(*wd)),
        Type::Bytes(wd) => format!("readBytes{}(r)", w(*wd)),
        Type::List(wd, inner) => format!(
            "readList{}(r, (r) => {})",
            w(*wd),
            decode_expr(schema, inner)
        ),
        Type::Opt(inner) => format!(
            "readPresent(r) ? {} : undefined",
            decode_expr(schema, inner)
        ),
        Type::Record => "decodeRecord(r)".into(),
        Type::Records => "decodeRecords(r)".into(),
        Type::Named(name) => match schema.enum_named(name) {
            Some(e) if e.repr == Type::U8 => "readU8(r)".into(),
            Some(_) => "readU16(r)".into(),
            None => format!("decode{name}(r)"),
        },
    }
}

fn encode_stmt(schema: &Schema, ty: &Type, x: &str, ctx: &str, depth: usize) -> String {
    match ty {
        Type::U8 => format!("writeU8(w, {x});"),
        Type::U16 => format!("writeU16(w, {x});"),
        Type::U32 => format!("writeU32(w, {x});"),
        Type::U64 => format!("writeU64(w, {x});"),
        Type::I64 => format!("writeI64(w, {x});"),
        Type::Millis => format!("writeMillis(w, {x});"),
        Type::Bool => format!("writeU8(w, {x} ? 1 : 0);"),
        Type::F64 => format!("writeF64(w, {x});"),
        Type::Str(wd) => format!("writeStr{}(w, {x}, \"{ctx}\");", w(*wd)),
        Type::Bytes(wd) => format!("writeBytes{}(w, {x}, \"{ctx}\");", w(*wd)),
        Type::List(wd, inner) => {
            let item = format!("item{depth}");
            format!(
                "writeLen{}(w, {x}.length, \"{ctx}\");\n  for (const {item} of {x}) {{\n    {}\n  }}",
                w(*wd),
                encode_stmt(schema, inner, &item, ctx, depth + 1)
            )
        }
        Type::Opt(inner) => format!(
            "if ({x} === undefined) {{ writeU8(w, 0); }} else {{ writeU8(w, 1); {} }}",
            encode_stmt(schema, inner, x, ctx, depth + 1)
        ),
        Type::Record => format!("encodeRecord(w, {x});"),
        Type::Records => format!("encodeRecords(w, {x}, \"{ctx}\");"),
        Type::Named(name) => match schema.enum_named(name) {
            Some(e) if e.repr == Type::U8 => format!("writeU8(w, {x});"),
            Some(_) => format!("writeU16(w, {x});"),
            None => format!("encode{name}(w, {x});"),
        },
    }
}

pub fn emit_codec(schema: &Schema, schema_hash: &str) -> String {
    let mut o = String::new();
    header(&mut o);
    writeln!(o).unwrap();
    writeln!(o, "/** The protocol version this code speaks. */").unwrap();
    writeln!(o, "export const PROTOCOL_VERSION = {};", schema.version).unwrap();
    writeln!(
        o,
        "/** CRC32C of the schema source, for checking generated code is in sync. */"
    )
    .unwrap();
    writeln!(o, "export const SCHEMA_HASH = \"{schema_hash}\";").unwrap();
    writeln!(o).unwrap();
    o.push_str(RUNTIME);

    for e in &schema.enums {
        emit_enum(&mut o, e);
    }
    for u in &schema.unions {
        emit_union(&mut o, schema, u);
    }
    for s in &schema.structs {
        emit_struct(&mut o, schema, s);
    }
    emit_records(&mut o);
    emit_frames(&mut o, schema);
    o
}

fn emit_enum(o: &mut String, e: &Enum) {
    writeln!(o).unwrap();
    jsdoc(o, "", &e.doc);
    writeln!(o, "export const {} = {{", e.name).unwrap();
    for v in &e.variants {
        jsdoc(o, "  ", &v.doc);
        writeln!(o, "  {}: {},", v.name, v.value).unwrap();
    }
    writeln!(o, "}} as const;").unwrap();
    writeln!(
        o,
        "/** Open on decode: values this version does not know are kept. */"
    )
    .unwrap();
    writeln!(o, "export type {} = number;", e.name).unwrap();
    writeln!(
        o,
        "export const {}Names: Readonly<Record<number, string>> = {{",
        e.name
    )
    .unwrap();
    for v in &e.variants {
        writeln!(o, "  {}: \"{}\",", v.value, v.name).unwrap();
    }
    writeln!(o, "}};").unwrap();
}

fn emit_struct(o: &mut String, schema: &Schema, s: &Struct) {
    writeln!(o).unwrap();
    jsdoc(o, "", &s.doc);
    if s.fields.is_empty() {
        writeln!(o, "export type {} = Record<string, never>;", s.name).unwrap();
    } else {
        writeln!(o, "export type {} = {{", s.name).unwrap();
        for f in &s.fields {
            jsdoc(o, "  ", &f.doc);
            let optional = if matches!(f.ty, Type::Opt(_)) {
                "?"
            } else {
                ""
            };
            writeln!(
                o,
                "  {}{optional}: {};",
                camel(&f.name),
                ts_type(schema, &f.ty)
            )
            .unwrap();
        }
        writeln!(o, "}};").unwrap();
    }
    writeln!(o).unwrap();
    let r = if s.fields.is_empty() { "_r" } else { "r" };
    writeln!(
        o,
        "export function decode{}({r}: Reader): {} {{",
        s.name, s.name
    )
    .unwrap();
    if s.fields.is_empty() {
        writeln!(o, "  return {{}};").unwrap();
    } else {
        // Fields must be read in declaration order; object literal
        // properties are evaluated in source order, so this is it.
        writeln!(o, "  return {{").unwrap();
        for f in &s.fields {
            writeln!(o, "    {}: {},", camel(&f.name), decode_expr(schema, &f.ty)).unwrap();
        }
        writeln!(o, "  }};").unwrap();
    }
    writeln!(o, "}}").unwrap();
    writeln!(o).unwrap();
    let (wv, v) = if s.fields.is_empty() {
        ("_w", "_v")
    } else {
        ("w", "v")
    };
    writeln!(
        o,
        "export function encode{}({wv}: Writer, {v}: {}): void {{",
        s.name, s.name
    )
    .unwrap();
    for f in &s.fields {
        let ctx = format!("{}.{}", s.name, f.name);
        writeln!(
            o,
            "  {}",
            encode_stmt(schema, &f.ty, &format!("v.{}", camel(&f.name)), &ctx, 0)
        )
        .unwrap();
    }
    writeln!(o, "}}").unwrap();
}

fn emit_records(o: &mut String) {
    let e = EVENT_RECORD;
    write!(
        o,
        r#"
/**
 * One event record: `len u32 | flags u8 | body`, the stored layout without
 * its leading CRC. `flags` is 0 for an event (see `{e}`).
 */
export type StoredRecord = {{
  flags: number;
  event: {e};
}};

export function decodeRecord(r: Reader): StoredRecord {{
  const len = readU32(r);
  if (len === 0) throw new ProtocolError("zero-length record");
  const flags = readU8(r);
  const end = r.pos + len - 1;
  if (end > r.end) throw new ProtocolError("record extends past the frame");
  const body = reader(r.buf, r.pos, end);
  const event = decode{e}(body);
  if (body.pos !== end) throw new ProtocolError("record body has trailing bytes");
  r.pos = end;
  return {{ flags, event }};
}}

export function encodeRecord(w: Writer, rec: StoredRecord): void {{
  const lenAt = w.pos;
  writeU32(w, 0);
  writeU8(w, rec.flags);
  const start = w.pos;
  encode{e}(w, rec.event);
  w.view.setUint32(lenAt, 1 + (w.pos - start), true);
}}

export function decodeRecords(r: Reader): StoredRecord[] {{
  const n = readU32(r);
  const out: StoredRecord[] = [];
  for (let i = 0; i < n; i++) out.push(decodeRecord(r));
  return out;
}}

export function encodeRecords(w: Writer, recs: StoredRecord[], ctx: string): void {{
  writeLen32(w, recs.length, ctx);
  for (const rec of recs) encodeRecord(w, rec);
}}
"#
    )
    .unwrap();
}

fn emit_frames(o: &mut String, schema: &Schema) {
    writeln!(o).unwrap();
    writeln!(
        o,
        "/** Frame kinds. Kinds with the 0x8000 bit are sent by the server. */"
    )
    .unwrap();
    writeln!(o, "export const FrameKind = {{").unwrap();
    for f in schema.frames() {
        writeln!(o, "  {}: {:#06x},", f.name, f.kind.unwrap()).unwrap();
    }
    writeln!(o, "}} as const;").unwrap();
    writeln!(o).unwrap();
    writeln!(
        o,
        "/** Every frame this version knows, discriminated by `name`. */"
    )
    .unwrap();
    writeln!(o, "export type Frame =").unwrap();
    for f in schema.frames() {
        writeln!(o, "  | {{ name: \"{0}\"; body: {0} }}", f.name).unwrap();
    }
    writeln!(o, "  ;").unwrap();
    writeln!(o).unwrap();
    writeln!(o, "/**").unwrap();
    writeln!(
        o,
        " * Decodes a frame body. `undefined` for a kind this version does not know."
    )
    .unwrap();
    writeln!(
        o,
        " * Bytes after the declared fields are ignored: later minor versions may"
    )
    .unwrap();
    writeln!(o, " * append fields to a frame.").unwrap();
    writeln!(o, " */").unwrap();
    writeln!(
        o,
        "export function decodeFrameBody(kind: number, r: Reader): Frame | undefined {{"
    )
    .unwrap();
    writeln!(o, "  switch (kind) {{").unwrap();
    for f in schema.frames() {
        writeln!(
            o,
            "    case {:#06x}: return {{ name: \"{1}\", body: decode{1}(r) }};",
            f.kind.unwrap(),
            f.name
        )
        .unwrap();
    }
    writeln!(o, "    default: return undefined;").unwrap();
    writeln!(o, "  }}").unwrap();
    writeln!(o, "}}").unwrap();
    writeln!(o).unwrap();
    writeln!(
        o,
        "/** Appends a whole frame — header and body — to `w`. */"
    )
    .unwrap();
    writeln!(o, "export function encodeFrame(w: Writer, stream: number, flags: number, frame: Frame): void {{").unwrap();
    writeln!(o, "  const start = w.pos;").unwrap();
    writeln!(o, "  writeU32(w, 0);").unwrap();
    writeln!(o, "  writeU16(w, FrameKind[frame.name]);").unwrap();
    writeln!(o, "  writeU8(w, flags);").unwrap();
    writeln!(o, "  writeU32(w, stream);").unwrap();
    writeln!(o, "  switch (frame.name) {{").unwrap();
    for f in schema.frames() {
        writeln!(
            o,
            "    case \"{0}\": encode{0}(w, frame.body); break;",
            f.name
        )
        .unwrap();
    }
    writeln!(o, "  }}").unwrap();
    writeln!(o, "  w.view.setUint32(start, w.pos - start - 4, true);").unwrap();
    writeln!(o, "}}").unwrap();
}

